import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

import { catalogDir, generateCatalog } from './generate-catalog.js';

/**
 * Emit `supabase/seed.sql` from the generated catalog.
 *
 * The seed is idempotent: every statement is an upsert keyed on the primary
 * key, so running it twice leaves the database in the same state. That means
 * the seed can be re-run after any catalog change without a manual reset.
 */

function quote(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function literal(value: string | null): string {
  if (value === null) return 'null';
  return quote(value);
}

function number(value: number | undefined): string {
  return value === undefined ? 'null' : String(value);
}

export function buildSeed(): string {
  const { catalog, queries } = generateCatalog();
  const lines: string[] = [];

  lines.push('-- POLARIS seed data');
  lines.push('--');
  lines.push('-- Generated by `npm run seed --workspace @polaris/catalog`. Do not edit by');
  lines.push('-- hand: the catalog is generated, and the seed is generated from it.');
  lines.push('--');
  lines.push('-- Every statement is an upsert on the primary key, so the seed is');
  lines.push('-- idempotent and can be re-run after a catalog change.');
  lines.push('');
  lines.push('begin;');
  lines.push('');

  lines.push('-- 240 tools');
  lines.push(
    'insert into tools (id, category, name, description, descriptor, input_schema, x, y) values',
  );
  const toolRows = catalog.tools.map(
    (tool) =>
      `  (${quote(tool.id)}, ${quote(tool.category)}, ${quote(tool.name)}, ${quote(tool.description)}, ${quote(tool.descriptor)}, ${quote(JSON.stringify(tool.parameters ?? {}))}::jsonb, ${number(tool.x)}, ${number(tool.y)})`,
  );
  lines.push(toolRows.join(',\n'));
  lines.push('on conflict (id) do update set');
  lines.push('  category = excluded.category,');
  lines.push('  name = excluded.name,');
  lines.push('  description = excluded.description,');
  lines.push('  descriptor = excluded.descriptor,');
  lines.push('  input_schema = excluded.input_schema,');
  lines.push('  x = excluded.x,');
  lines.push('  y = excluded.y;');
  lines.push('');

  lines.push(`-- ${queries.counts.total} evaluation queries`);
  lines.push('insert into eval_queries (id, query, label_tool, kind, split) values');
  const queryRows = queries.queries.map(
    (query) =>
      `  (${quote(query.id)}, ${quote(query.query)}, ${literal(query.labelTool)}, ${quote(query.kind)}, ${quote(query.split)})`,
  );
  lines.push(queryRows.join(',\n'));
  lines.push('on conflict (id) do update set');
  lines.push('  query = excluded.query,');
  lines.push('  label_tool = excluded.label_tool,');
  lines.push('  kind = excluded.kind,');
  lines.push('  split = excluded.split;');
  lines.push('');

  lines.push('commit;');
  lines.push('');

  return lines.join('\n');
}

export async function writeSeed(path: string): Promise<{ path: string; bytes: number }> {
  await mkdir(dirname(path), { recursive: true });
  const body = buildSeed();
  await writeFile(path, body, 'utf8');
  return { path, bytes: Buffer.byteLength(body) };
}

export function seedPath(): string {
  return resolve(catalogDir(), '..', 'supabase', 'seed.sql');
}
